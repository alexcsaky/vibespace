  money: ['..#####..', '.#.....#.', '#...#...#', '#..###..#', '#...#...#', '#..###..#', '#...#...#', '.#.....#.', '..#####..'],
  people: ['.##...##.', '.##...##.', '.........', '####.####', '####.####', '####.####', '####.####', '.........', '.........'],
  skills: ['.#####...', '#######..', '.#####...', '...#.....', '...#.....', '...#.....', '...#.....', '...#.....', '...#.....'],
  drop: ['....#....', '...###...', '...###...', '..#####..', '.#######.', '.#######.', '.#######.', '..#####..', '...###...'],
